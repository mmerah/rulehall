from collections.abc import Awaitable, Callable, Sequence
from dataclasses import dataclass
from random import Random
from typing import Protocol

from rulehall.core.facts import Fact, Resolution
from rulehall.core.game import AnyGame, RoleAnswer
from rulehall.core.validation import Frozen


class Transport(Protocol):
    async def send(self, lines: Sequence[str]) -> None: ...
    async def receive(self) -> tuple[str, ...]: ...
    async def close(self) -> None: ...


type StartTransport = Callable[[tuple[str, ...]], Awaitable[Transport]]


@dataclass(frozen=True, slots=True, kw_only=True)
class BattleServices:
    opponent: RoleAnswer | None
    start_transport: StartTransport


class BattleRun(Protocol):
    @property
    def resolution(self) -> Resolution | None: ...
    def view(self, state: AnyGame, /) -> Frozen: ...
    def log(self, state: AnyGame, /) -> Sequence[str]: ...
    def facts(self, state: AnyGame, /) -> Sequence[Fact]: ...
    def require_command(self, state: AnyGame, command: str, /) -> None: ...
    async def choose(self, draft: AnyGame, command: str, rng: Random) -> None: ...
    async def close(self) -> None: ...


class BattleSupport(Protocol):
    def in_battle(self, state: AnyGame, /) -> bool: ...
    async def open_battle(self, draft: AnyGame, services: BattleServices, /) -> BattleRun: ...
